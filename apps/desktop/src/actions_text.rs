pub fn error_text(kind: ErrorKind) -> ActionText {
    match kind {
        ErrorKind::CliMissing
        | ErrorKind::CliOverrideInvalid
        | ErrorKind::CliNotExecutable
        | ErrorKind::LaunchFailed => ActionText::CliMissingError,
        ErrorKind::CliVersionMismatch | ErrorKind::CliChanged => ActionText::CliMismatchError,
        ErrorKind::GatewayUnavailable => ActionText::GatewayError,
        ErrorKind::ModelUnavailable | ErrorKind::InvalidModel => ActionText::ModelError,
        ErrorKind::ConfigConflict | ErrorKind::AlreadyManaged | ErrorKind::NotManaged => {
            ActionText::ConfigChangedError
        }
        ErrorKind::ConfigInvalid | ErrorKind::InvalidConfigPath | ErrorKind::RecoveryRequired => {
            ActionText::ConfigError
        }
        ErrorKind::ConfigReadOnly => ActionText::PermissionError,
        ErrorKind::TimedOut => ActionText::TimeoutError,
        ErrorKind::Cancelled => ActionText::CancelledError,
        ErrorKind::InvalidReply | ErrorKind::OutputTooLarge => ActionText::InvalidReplyError,
        ErrorKind::CleanupPending => ActionText::CleanupError,
        ErrorKind::PlatformUnsupported => ActionText::WindowsHint,
        ErrorKind::InvalidAddress => ActionText::InvalidAddressError,
        ErrorKind::Busy | ErrorKind::CliRejected => ActionText::OtherError,
    }
}
