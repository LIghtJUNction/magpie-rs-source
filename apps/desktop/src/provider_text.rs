pub(crate) fn error_text(locale: Locale, code: &str) -> &'static str {
    let key = match code {
        "provider_revision_conflict" | "provider_conflict" => P::Conflict,
        "provider_draft_conflict" => P::DraftConflict,
        "provider_read_conflict" => P::ReadConflict,
        "provider_read_unsupported" => P::ReadUnsupported,
        "provider_credential_unavailable"
        | "provider_credential_invalid"
        | "provider_keys_paused"
        | "provider_key_paused" => P::CredentialError,
        "provider_http_401" | "provider_http_403" => P::AuthError,
        "provider_http_429" => P::RateLimit,
        "provider_timeout" | "provider_transport" | "provider_transport_error" => P::NetworkError,
        "provider_protocol_not_integrated"
        | "provider_platform_unsupported"
        | "provider_lock_unsupported" => P::Unavailable,
        "provider_busy" | "busy" => P::Busy,
        "operation_cancelled" | "cancelled" => P::Cancelled,
        "provider_store_too_large"
        | "provider_models_limit"
        | "provider_collection_limit"
        | "provider_keys_limit"
        | "output_limit"
        | "provider_input_too_large" => P::TooLarge,
        "provider_insecure_permissions" => P::InsecurePermissions,
        "provider_recovery_required" => P::Recovery,
        "provider_recovery_guard_present"
        | "provider_recovery_conflict"
        | "provider_unknown_recovery_material"
        | "provider_unknown_lock"
        | "provider_lock_mismatch"
        | "provider_lock_owner_unverifiable" => P::RecoveryConflict,
        "provider_lock_failed" => P::GenericError,
        c if c.starts_with("provider_invalid")
            || c == "provider_selected_model_unknown"
            || c == "provider_insecure_http_requires_consent"
            || c == "provider_id_exists" =>
        {
            P::InvalidInput
        }
        _ => P::GenericError,
    };
    t(locale, key)
}
